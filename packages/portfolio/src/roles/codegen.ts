/**
 * The files a role reaches that cannot read the role files at runtime:
 * the two module indexes (a static import per file) and the Storybook story
 * exports (Storybook indexes stories by their static export names).
 * `bun run roles:sync` writes them; `codegen.test.ts` fails when one is
 * stale, so adding a role is: its role file, its market research,
 * then `roles:sync`.
 */
import { readdirSync, readFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';
import { basename, join, relative } from 'node:path';

export { variantNamesFor, type SchemeOf } from './codegen-names';

const SRC = join(import.meta.dir, '..');
export const ROLE_FILES_DIR = join(SRC, 'roles', 'by-id');
export const RESEARCH_DIR = join(SRC, 'market', 'research');
/** The cross-cutting findings live beside the research but are not one. */
const FINDINGS_FILE = 'market.json';

export const START = '// role-variants:start (bun run roles:sync)';
export const END = '// role-variants:end';

const HEADER = '// Generated by `bun run roles:sync`. Do not edit.\n';

const camel = (id: string): string =>
  id.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());

const filesIn = (dir: string, suffix: string): string[] =>
  readdirSync(dir)
    .filter((name) => name.endsWith(suffix) && !name.startsWith('index.'))
    .sort();

export const roleFileIds = (): string[] =>
  filesIn(ROLE_FILES_DIR, '.ts')
    .filter((name) => !name.endsWith('.test.ts'))
    .map((name) => basename(name, '.ts'));

export const researchIds = (): string[] =>
  filesIn(RESEARCH_DIR, '.json')
    .filter((name) => name !== FINDINGS_FILE)
    .map((name) => basename(name, '.json'));

export const roleIndexSource = (ids: readonly string[]): string =>
  `${HEADER}/** Every role, one file each. */\n${ids
    .map((id) => `import ${camel(id)} from './${id}';`)
    .join('\n')}\n\nexport const ROLE_DEFINITIONS = [\n${ids
    .map((id) => `  ${camel(id)},`)
    .join('\n')}\n] as const;\n`;

export const researchIndex = (ids: readonly string[]): string =>
  `${HEADER}/** Every market research, keyed by role id; parsed in \`../research.ts\`. */\n${ids
    .map((id) => `import ${camel(id)} from './${id}.json';`)
    .join(
      '\n'
    )}\n\nexport const RESEARCH_FILES: Readonly<Record<string, unknown>> = {\n${ids
    .map((id) => `  '${id}': ${camel(id)},`)
    .join('\n')}\n};\n`;

/** The generated block of a story file: one export per variant. */
export const variantBlock = (names: readonly string[]): string =>
  [
    START,
    ...names.map((name) => `export const ${name} = variant('${name}');`),
    END,
  ].join('\n');

const BLOCK = new RegExp(
  `${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`
);

/** A story file with its variant block brought up to date. */
export const withVariants = (
  source: string,
  names: readonly string[]
): string => {
  if (!BLOCK.test(source)) {
    throw new Error(`no "${START}" block`);
  }
  return source.replace(BLOCK, variantBlock(names));
};

/** One role's details screen, in every variant. */
export const detailStory = (id: string, names: readonly string[]): string =>
  `${HEADER}import { ROLE_ARG_TYPES, variant } from '../stories/variants';
import Chrome from '../layouts/Chrome.astro';
import RoleDetailScreen from './RoleDetailScreen.astro';

export default {
  title: 'Screens/Role details/${id}',
  component: RoleDetailScreen,
  args: { subject: '${id}' },
  decorators: [
    (_story: unknown, context: { args: Record<string, unknown> }) => ({
      component: Chrome,
      props: { role: context.args['role'] },
    }),
  ],
  argTypes: ROLE_ARG_TYPES,
};

${variantBlock(names)}
`;

export const detailStoryPath = (id: string): string =>
  join(SRC, 'screens', `role-details-${id}.stories.ts`);

const storyFiles = (dir: string): string[] =>
  readdirSync(join(SRC, dir), { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? storyFiles(join(dir, entry.name))
      : entry.name.endsWith('.stories.ts')
        ? [join(SRC, dir, entry.name)]
        : []
  );

export const STORY_DIRS = ['components', 'screens', 'stories', 'design-system'];

/**
 * Every generated file and the content it should have. Detail stories are
 * whole files; other story files only have their variant block replaced.
 */
export const expectedFiles = (
  variantNames: readonly string[]
): Map<string, string> => {
  const ids = roleFileIds();
  const files = new Map<string, string>([
    [join(ROLE_FILES_DIR, 'index.ts'), roleIndexSource(ids)],
    [join(RESEARCH_DIR, 'index.ts'), researchIndex(researchIds())],
  ]);
  for (const id of ids) {
    files.set(detailStoryPath(id), detailStory(id, variantNames));
  }
  for (const path of STORY_DIRS.flatMap(storyFiles)) {
    if (files.has(path) || basename(path).startsWith('role-details-')) {
      continue;
    }
    files.set(path, withVariants(readFileSync(path, 'utf8'), variantNames));
  }
  return files;
};

/** The generated files as the repository's formatter would leave them. */
export const formattedExpectedFiles = async (
  variantNames: readonly string[]
): Promise<Map<string, string>> => {
  const files = expectedFiles(variantNames);
  const out = new Map<string, string>();
  for (const [path, content] of files) {
    const options = (await resolveConfig(path)) ?? {};
    out.set(path, await format(content, { ...options, filepath: path }));
  }
  return out;
};

/** Generated detail stories whose role is gone. */
export const orphanedFiles = (): string[] => {
  const ids = new Set(roleFileIds());
  return readdirSync(join(SRC, 'screens'))
    .filter((name) => /^role-details-.*\.stories\.ts$/.test(name))
    .filter(
      (name) =>
        !ids.has(basename(name, '.stories.ts').replace('role-details-', ''))
    )
    .map((name) => join(SRC, 'screens', name));
};

export const relativeToSrc = (path: string): string => relative(SRC, path);
